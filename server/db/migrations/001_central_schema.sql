-- Atomically consolidate two legacy browser-created installation rows into one
-- canonical physical device. The source row is retained as a migration/audit
-- alias, while dependent customer history is re-parented to the target.
create or replace function public.merge_physical_installations(
  source_id uuid,
  target_id uuid
) returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  src public.installations%rowtype;
  dst public.installations%rowtype;
  source_customer uuid;
begin
  if source_id is null or target_id is null or source_id = target_id then
    return target_id;
  end if;

  select * into src from public.installations where id = source_id for update;
  select * into dst from public.installations where id = target_id for update;

  if src.id is null or dst.id is null then
    raise exception 'Installation not found';
  end if;

  if dst.merged_into_installation_id is not null then
    select * into dst
    from public.installations
    where id = dst.merged_into_installation_id
    for update;
    target_id := dst.id;
  end if;

  if src.merged_into_installation_id = target_id then
    return target_id;
  end if;

  source_customer := src.customer_id;

  update public.installations
  set
    status = case when src.status = 'BLOCKED' or dst.status = 'BLOCKED' then 'BLOCKED' else 'ACTIVE' end,
    trial_started_at = least(src.trial_started_at, dst.trial_started_at),
    -- Never extend a trial merely because the same computer was registered in
    -- another browser. The earliest server-issued trial end wins.
    trial_ends_at = least(src.trial_ends_at, dst.trial_ends_at),
    subscription_expires_at = case
      when src.subscription_expires_at is null then dst.subscription_expires_at
      when dst.subscription_expires_at is null then src.subscription_expires_at
      else greatest(src.subscription_expires_at, dst.subscription_expires_at)
    end,
    last_seen_at = case
      when src.last_seen_at is null then dst.last_seen_at
      when dst.last_seen_at is null then src.last_seen_at
      else greatest(src.last_seen_at, dst.last_seen_at)
    end,
    last_license_check_at = case
      when src.last_license_check_at is null then dst.last_license_check_at
      when dst.last_license_check_at is null then src.last_license_check_at
      else greatest(src.last_license_check_at, dst.last_license_check_at)
    end,
    access_version = greatest(coalesce(src.access_version, 1), coalesce(dst.access_version, 1), (extract(epoch from clock_timestamp()) * 1000)::bigint),
    physical_device_id = target_id,
    physical_fingerprint_hash = coalesce(dst.physical_fingerprint_hash, src.physical_fingerprint_hash),
    coarse_fingerprint_hash = coalesce(dst.coarse_fingerprint_hash, src.coarse_fingerprint_hash),
    fingerprint_version = coalesce(dst.fingerprint_version, src.fingerprint_version),
    fingerprint_strength = greatest(coalesce(dst.fingerprint_strength, 0), coalesce(src.fingerprint_strength, 0)),
    last_network_hash = coalesce(src.last_network_hash, dst.last_network_hash),
    display_name = coalesce(nullif(dst.display_name, ''), nullif(src.display_name, '')),
    profile_name = coalesce(nullif(dst.profile_name, ''), nullif(src.profile_name, '')),
    profile_logo = coalesce(nullif(dst.profile_logo, ''), nullif(src.profile_logo, '')),
    app_version = coalesce(src.app_version, dst.app_version)
  where id = target_id;

  update public.browser_installations set installation_id = target_id, updated_at = now() where installation_id = source_id;
  update public.subscriptions set installation_id = target_id where installation_id = source_id;
  update public.provider_messages set installation_id = target_id where installation_id = source_id;
  update public.access_events set installation_id = target_id where installation_id = source_id;
  update public.device_events set installation_id = target_id where installation_id = source_id;
  update public.payment_requests set installation_id = target_id where installation_id = source_id;
  update public.customer_notifications set installation_id = target_id where installation_id = source_id;
  update public.innovations set requested_by_installation_id = target_id where requested_by_installation_id = source_id;

  -- Innovation feedback allows one vote per innovation/device. Remove only the
  -- duplicate source vote when the canonical device has already voted.
  delete from public.innovation_feedback s
  where s.installation_id = source_id
    and exists (
      select 1 from public.innovation_feedback t
      where t.installation_id = target_id
        and t.innovation_id = s.innovation_id
    );
  update public.innovation_feedback set installation_id = target_id where installation_id = source_id;

  update public.installations
  set
    customer_id = dst.customer_id,
    physical_device_id = target_id,
    merged_into_installation_id = target_id,
    merged_at = now()
  where id = source_id;

  -- Old code paths may still query the legacy installation token. Keeping the
  -- source row is intentional; browser_installations now resolves that token to
  -- the canonical target before the legacy lookup is attempted.

  if source_customer is distinct from dst.customer_id
     and not exists (select 1 from public.installations where customer_id = source_customer) then
    delete from public.service_customers where id = source_customer;
  end if;

  return target_id;
end;
$$;


