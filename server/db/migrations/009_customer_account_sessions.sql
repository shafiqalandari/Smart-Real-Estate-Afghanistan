-- SafarPro customer account authentication and single-active-browser migration.
-- Safe and additive: no existing customer, installation, subscription or business data is deleted.

begin;

create table if not exists public.customer_accounts (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid not null unique references public.service_customers(id) on delete cascade,
  email text not null,
  password_salt text not null,
  password_hash text not null,
  registered_company_id uuid references public.registered_companies(id) on delete set null,
  status text not null default 'ACTIVE' check (status in ('ACTIVE','DISABLED')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_login_at timestamptz
);
create unique index if not exists customer_accounts_email_unique on public.customer_accounts (lower(email));
create index if not exists customer_accounts_customer_idx on public.customer_accounts(customer_id);

create table if not exists public.customer_login_events (
  id bigint generated by default as identity primary key,
  customer_id uuid references public.service_customers(id) on delete cascade,
  installation_id uuid references public.installations(id) on delete set null,
  email text,
  event_type text not null,
  success boolean not null default true,
  ip_address text,
  user_agent text,
  browser text,
  operating_system text,
  reason text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists customer_login_events_customer_idx on public.customer_login_events(customer_id, created_at desc);
create index if not exists customer_login_events_installation_idx on public.customer_login_events(installation_id, created_at desc);
create index if not exists customer_login_events_email_idx on public.customer_login_events(lower(email), created_at desc);

alter table if exists public.installations
  add column if not exists session_state text not null default 'ACTIVE',
  add column if not exists revoked_at timestamptz,
  add column if not exists revoked_reason text,
  add column if not exists login_ip text,
  add column if not exists last_ip text;

update public.installations set session_state='ACTIVE' where session_state is null;

do $$
begin
  if not exists (select 1 from pg_constraint where conname='installations_session_state_check') then
    alter table public.installations add constraint installations_session_state_check check (session_state in ('ACTIVE','REVOKED'));
  end if;
end $$;

alter table if exists public.browser_installations
  add column if not exists session_state text not null default 'ACTIVE',
  add column if not exists revoked_at timestamptz,
  add column if not exists revoked_reason text,
  add column if not exists ip_address text;

update public.browser_installations set session_state='ACTIVE' where session_state is null;

do $$
begin
  if not exists (select 1 from pg_constraint where conname='browser_installations_session_state_check') then
    alter table public.browser_installations add constraint browser_installations_session_state_check check (session_state in ('ACTIVE','REVOKED'));
  end if;
end $$;

create index if not exists installations_customer_session_idx on public.installations(customer_id, session_state, created_at desc);
create index if not exists browser_installations_session_idx on public.browser_installations(installation_id, session_state, last_seen_at desc);

alter table public.customer_accounts enable row level security;
alter table public.customer_login_events enable row level security;

commit;
